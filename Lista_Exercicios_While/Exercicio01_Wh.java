// Exercício 1: Escreva um algoritmo que imprima a sequência do número 100 ao 200.

public class Exercicio01_Wh {

    public static void main(String[] args) {
        int algoritmo = 100;

        while (algoritmo <= 200) {
            System.out.println(algoritmo + " ");
            algoritmo++;
        }
    }
}
